void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  
  try {
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );
    await NotificationService.initialize();
  } catch (e) {
    print('Firebase initialization error: $e');
  }

  await DiagnosisService.initialize();

  await Hive.initFlutter();
  await Hive.openBox('user_preferences');

  await dotenv.load(fileName: ".env");

  // Test Gemini Connection (Removed to prevent quota exhaustion)
  // GeminiService().testConnection();

  final prefs = await SharedPreferences.getInstance();

  runApp(
    ProviderScope(
      overrides: [
        sharedPreferencesProvider.overrideWithValue(prefs),
      ],
      child: const AgriDxApp(),
    ),
  );
}

class AgriDxApp extends StatelessWidget {
  const AgriDxApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'AgriDx',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        primaryColor: const Color(0xFF2E7D32),
        colorScheme: ColorScheme.fromSeed(
          seedColor: const Color(0xFF2E7D32),
          primary: const Color(0xFF2E7D32),
          secondary: const Color(0xFF4CAF50),
        ),
        useMaterial3: true,
        scaffoldBackgroundColor: const Color(0xFFFAFAFA),
        textTheme: GoogleFonts.outfitTextTheme(Theme.of(context).textTheme),
        pageTransitionsTheme: const PageTransitionsTheme(
          builders: {
            TargetPlatform.android: FadeUpwardsPageTransitionsBuilder(),
            TargetPlatform.iOS: CupertinoPageTransitionsBuilder(),
          },
        ),
      ),
      builder: (context, child) => AppConstraints(child: child!),
      home: const AuthWrapper(),
    );
  }
}

class AuthWrapper extends ConsumerWidget {
  const AuthWrapper({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final authState = ref.watch(authStateProvider);

    return authState.when(
      data: (user) {
        final isGuestMode = Hive.box('user_preferences').get('isGuestMode', defaultValue: false);
        
        if (user != null || isGuestMode) {
          return const MainNavigationWrapper();
        }
        
        final hasSeenOnboarding = Hive.box('user_preferences').get('hasSeenOnboarding', defaultValue: false);
        if (!hasSeenOnboarding) {
          return const OnboardingScreen();
        }
        
        return const LoginScreen();
      },
      loading: () => const Scaffold(
        body: Center(
          child: CircularProgressIndicator(color: Color(0xFF1B5E20)),
        ),
      ),
      error: (e, trace) => Scaffold(
        body: Center(
          child: Text('Authentication Error: $e'),
        ),
      ),
    );
  }
}
